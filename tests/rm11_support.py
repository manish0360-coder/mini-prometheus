def raw_job(
    request_id: str, operations: list[tuple[str, object]], *, material: str = "Aluminum 6061"
) -> dict:
    """A request whose operations carry the given duration_min (None = no duration declared)."""
    declared = []
    for op, duration in operations:
        entry: dict = {"op": op}
        if duration is not None:
            entry["params"] = {"duration_min": duration}
        declared.append(entry)
    return {
        "schema_version": "1.0.0",
        "request_id": request_id,
        "material": material,
        "stock_form": "block",
        "declared_operations": declared,
        "quantity": 1,
    }


def request(request_id: str, operations: list[tuple[str, object]], **kwargs):
    return support.build_request(raw_job(request_id, operations, **kwargs))


