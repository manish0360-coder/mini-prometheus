def schedule(requests, model: ProcessCapabilityModel | None = None, produced_at: str = FIXED_TIME):
    return schedule_requests(requests, capability_model=model, produced_at=produced_at)


def scheduling_jobs(requests, model: ProcessCapabilityModel | None = None) -> list[SchedulingJob]:
    """The schedulable jobs of a request list (every prerequisite asserted), in the given order."""
    model = model or default_model()
    jobs = []
    for req in requests:
        design_input = intake(req, produced_at=FIXED_TIME)
        task, plan = planner.plan(design_input, model, produced_at=FIXED_TIME)
        verdict = ManufacturabilityOracle().verify(plan, model)
        assert job_prerequisite_refusals(req.request_id, design_input, plan, verdict) == []
        jobs.append(SchedulingJob(req.request_id, task.task_id, plan))
    return jobs


def placements(sched) -> list[tuple]:
    return [
        (o.request_id, o.step_index, o.op, o.resource_id, o.start_min, o.end_min)
        for o in sched.operations
    ]


def twin_model() -> ProcessCapabilityModel:
    """default_model() plus a second mill (mill02) — the RM9 reroute test model."""
    base = default_model()
    return ProcessCapabilityModel(
        version=base.version,
        op_capability=base.op_capability,
        resources={**base.resources, "mill02": frozenset({"cap.mill", "cap.drill"})},
        supported_materials=base.supported_materials,
    )
