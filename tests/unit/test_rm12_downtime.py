# ---- identity (L) and routing (S, T) ----
def test_L_relevant_downtime_changes_identity_rule_and_schedule():
    base = s.schedule(s.shared_machine_requests()).schedule
    down = _run(s.shared_machine_requests(), {"saw01": [(0, 5)]})
    assert _placements(down) == [
        ("A", 0, "cut_stock", "saw01", 5, 15),
        ("B", 0, "cut_stock", "saw01", 15, 25),
        ("B", 1, "face_mill", "mill01", 25, 125),
    ]
    assert (down.scheduling_rule, base.scheduling_rule) == (
        "earliest_start_v1_downtime",
        "earliest_start_v1",
    )
    assert down.schedule_input_identity != base.schedule_input_identity
    assert down.schedule_digest != base.schedule_digest
    later = _run(s.shared_machine_requests(), {"mill01": [(1000, 1010)]})  # used machine, no effect
    assert [(o.start_min, o.end_min) for o in later.operations] == [
        (o.start_min, o.end_min) for o in base.operations
    ]
    assert later.schedule_input_identity != base.schedule_input_identity  # relevance = machine used


