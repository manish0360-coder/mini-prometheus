def _run(requests, downtime, model=None, produced_at=FIXED_TIME):
    outcome = schedule_requests(
        requests, capability_model=model, produced_at=produced_at, downtime=downtime
    )
    assert outcome.status == ScheduleStatus.SCHEDULED and outcome.refusals == ()
    return outcome.schedule


def _placements(sched):
    return [
        (LETTER[o.request_id], o.step_index, o.op, o.resource_id, o.start_min, o.end_min)
        for o in sched.operations
    ]


def _single(duration, downtime, op="face_mill"):
    sched = _run([s.request(ID_A, [(op, duration)])], downtime)
    ((_letter, _step, _op, _machine, start, end),) = _placements(sched)
    return start, end


# ---- canonicalization and validation (D, E, M-R) ----
def test_D_overlapping_intervals_are_merged():
    assert canonical_downtime({"mill01": [(50, 100), (75, 130)]}, KNOWN) == {
        "mill01": (D(50, 130),)
    }


def test_E_touching_intervals_are_merged():
    assert canonical_downtime({"mill01": [(60, 120), (120, 180)]}, KNOWN) == {
        "mill01": (D(60, 180),)
    }


def test_canonical_form_is_sorted_disjoint_non_touching_and_order_independent():
    spans = [(300, 310), (10, 50), (20, 30), (10, 50), (49, 60), D(59, 61)]
    expected = {"mill01": (D(10, 61), D(300, 310)), "saw01": (D(0, 1),)}
    for order in itertools.permutations(spans[:4]):
        given = {"saw01": [(0, 1)], "mill01": [*order, *spans[4:]], "lathe01": []}
        result = canonical_downtime(given, KNOWN)
        assert result == expected and list(result) == ["mill01", "saw01"]  # empty machine omitted
    assert canonical_downtime(None, KNOWN) == {} == canonical_downtime({}, KNOWN)


def test_M_unknown_machine_is_rejected_never_ignored():
    with pytest.raises(InvalidDowntimeError, match="unknown machine id\\(s\\) in downtime: mill99"):
        canonical_downtime({"mill99": [(0, 10)], "mill01": [(0, 10)]}, KNOWN)
    with pytest.raises(InvalidDowntimeError, match="mill99"):  # before any planning or refusal
        schedule_requests([s.request(ID_A, [("cut_stock", None)])], downtime={"mill99": [(0, 1)]})


