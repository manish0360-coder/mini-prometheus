def test_input_identity_is_the_problem_including_relevant_downtime_not_the_answer():
    sched = _run(s.three_job_requests(), {"mill01": [(20, 45)]})
    jobs = s.scheduling_jobs(s.three_job_requests())
    relevant = relevant_downtime(canonical_downtime({"mill01": [(20, 45)]}, KNOWN), jobs)
    before = schedule_input_identity(
        "earliest_start_v1_downtime",
        "1.0.0",
        "1.0.0",
        [(j.request_id, j.plan.content_hash) for j in jobs],
        relevant,
    )
    assert sched.schedule_input_identity == before


