def test_04_job_precedence_preserved():
    sched = _scheduled(s.three_job_requests())
    assert s.placements(sched) == s.THREE_JOB_SCHEDULE
    for request_id in (ID_A, ID_B, ID_C):
        ops = sorted(
            (o for o in sched.operations if o.request_id == request_id), key=lambda o: o.step_index
        )
        assert [o.step_index for o in ops] == list(range(len(ops)))
        assert all(later.start_min >= earlier.end_min for earlier, later in itertools.pairwise(ops))


def test_05_machine_no_overlap_with_touching_intervals_allowed():
    sched = _scheduled(s.three_job_requests())
    for machine in sorted({o.resource_id for o in sched.operations}):
        intervals = sorted(
            (o.start_min, o.end_min) for o in sched.operations if o.resource_id == machine
        )
        assert all(nxt[0] >= prev[1] for prev, nxt in itertools.pairwise(intervals)), machine
    mill = sorted((o.start_min, o.end_min) for o in sched.operations if o.resource_id == "mill01")
    assert mill == [
        (10, 40),
        (40, 50),
        (50, 62),
    ]  # back-to-back: [a, b) then [b, c) is not an overlap


def test_06_exact_tie_is_decided_by_request_id_not_by_content_or_order():
    first = _scheduled(s.shared_machine_requests())  # the short saw job holds ID_A
    assert s.placements(first)[0] == (ID_A, 0, "cut_stock", "saw01", 0, 10)
