def test_18_fixed_machine_assignment_retained():
    sched = _scheduled(s.three_job_requests())
    jobs = s.scheduling_jobs(s.three_job_requests())
    assigned = {
        (j.request_id, a.step_index): a.resource_id
        for j in jobs
        for a in j.plan.resource_assignments
    }
    assert all(o.resource_id == assigned[(o.request_id, o.step_index)] for o in sched.operations)
    twin = _scheduled(s.three_job_requests(), s.twin_model())  # a second mill exists and sits idle
    assert {o.resource_id for o in twin.operations if o.op in MILL_OPS} == {"mill01"}
    assert s.placements(twin) == s.THREE_JOB_SCHEDULE  # no reassignment during RM11


def test_19_rm9_irrelevant_availability_keeps_identity_relevant_changes_it():
    twin = s.twin_model()
    base = _scheduled(s.three_job_requests(), twin)
    irrelevant = _scheduled(s.three_job_requests(), with_unavailable_resources(twin, ["mill02"]))
    relevant = _scheduled(s.three_job_requests(), with_unavailable_resources(twin, ["mill01"]))
    assert irrelevant == base
    assert relevant.schedule_input_identity != base.schedule_input_identity
    assert relevant.schedule_digest != base.schedule_digest
    assert {o.resource_id for o in relevant.operations if o.op in MILL_OPS} == {
        "mill02"
    }  # RM9 reroute
    assert [(o.start_min, o.end_min) for o in relevant.operations] == [
        (o.start_min, o.end_min) for o in base.operations
    ]
    default_base = _scheduled(s.shared_machine_requests())
    assert _scheduled(
        s.shared_machine_requests(), with_unavailable_resources(default_model(), ["lathe01"])
    ) == (default_base)


