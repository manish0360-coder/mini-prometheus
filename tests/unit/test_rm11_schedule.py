def test_input_identity_is_the_problem_not_the_answer():
    sched = _scheduled(s.three_job_requests())
    jobs = s.scheduling_jobs(s.three_job_requests())
    before_scheduling = schedule_input_identity(
        "earliest_start_v1",
        "1.0.0",
        "1.0.0",
        [(j.request_id, j.plan.content_hash) for j in reversed(jobs)],
    )
    assert sched.schedule_input_identity == before_scheduling
    other_answer = dataclasses.replace(sched, makespan_min=sched.makespan_min + 1)
    assert other_answer.schedule_input_identity == sched.schedule_input_identity
    assert schedule_digest(other_answer) != schedule_digest(sched) == sched.schedule_digest


