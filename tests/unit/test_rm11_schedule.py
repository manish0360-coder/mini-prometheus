    assert s.placements(swapped) == [
        (ID_A, 0, "cut_stock", "saw01", 0, 10),
        (ID_A, 1, "face_mill", "mill01", 10, 110),
        (ID_B, 0, "cut_stock", "saw01", 10, 20),
    ]
    assert (
        swapped.makespan_min,
        swapped.lower_bound_min,
        swapped.gap_to_lower_bound_min,
        swapped.bound_status,
    ) == (110, 110, 0, BoundStatus.PROVABLY_OPTIMAL)


