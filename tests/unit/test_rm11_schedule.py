def test_07_hash_seed_does_not_change_the_schedule():
    reference = _scheduled(s.three_job_requests())
    root = pathlib.Path(__file__).resolve().parents[2]
    code = textwrap.dedent("""
        import enum
        if not hasattr(enum, "StrEnum"):
            class StrEnum(str, enum.Enum):
                pass
            enum.StrEnum = StrEnum
        import rm11_support as s
        sched = s.schedule(s.three_job_requests()).schedule
        print(sched.schedule_input_identity, sched.schedule_digest)
    """)
    path = os.pathsep.join(str(p) for p in (root, root / "src", root / "tests"))
    outputs = {
        subprocess.run(
            [sys.executable, "-c", code],
            env={**os.environ, "PYTHONPATH": path, "PYTHONHASHSEED": seed},
            capture_output=True,
            text=True,
            check=True,
        ).stdout.strip()
        for seed in ("0", "1", "4242")
    }
    assert outputs == {f"{reference.schedule_input_identity} {reference.schedule_digest}"}


