# --- RM9 / RM13 boundaries ------------------------------------------------------------------------
def test_changeover_never_reroutes_to_another_machine():
    twin = s.twin_model()  # mill02 could take every mill operation; RM9's assignment stays fixed
    costly = t.run(s.three_job_requests(), [R("mill01", None, None, 100)], capability_model=twin)
    plain = t.run(s.three_job_requests(), capability_model=twin)

    def machines(outcome):
        return {(o.request_id, o.step_index): o.resource_id for o in outcome.schedule.operations}

    assert machines(costly) == machines(plain)
    assert costly.schedule.setups and costly.schedule.makespan_min > plain.schedule.makespan_min


def test_rm13_remaining_work_excludes_changeover():
    spec = {
        ID_A: [("face_mill", 10), ("deburr", 30)],
        ID_B: [("drill", 5), ("deburr", 15)],  # remaining processing 20, changeover 0
        ID_C: [("pocket_mill", 15)],  # remaining processing 15, changeover 10
    }
    rules = [R("mill01", None, None, 10), R("mill01", "face_mill", "drill", 0)]
    sched = _scheduled(spec, rules, rule=t.MWKR)
    assert sched.scheduling_rule == "earliest_start_v1_most_work_remaining_setup"
    # at t=10 B (20 processing) goes before C (15 processing + 10 changeover = 25 if it counted)
    mill = [o for o in sched.operations if o.resource_id == "mill01"]
    assert [(o.request_id, o.start_min, o.end_min) for o in mill] == [
        (ID_A, 0, 10),
        (ID_B, 10, 15),
        (ID_C, 25, 40),
    ]
    assert sched.makespan_min == 55


def test_the_generator_records_only_the_relevant_declared_rules():
    jobs = s.scheduling_jobs(t.requests_of(TWO_MILL))
    declared = (  # canonical, as the job set passes them; two rules cannot apply
        R("mill01", None, None, 9),
        R("mill01", "drill", "face_mill", 2),
        EXPLICIT[0],
        R("saw01", None, None, 5),
    )
    direct = earliest_start_v1(jobs, "1.0.0", setup_rules=declared)
    assert direct.setup_rules == (R("mill01", None, None, 9), EXPLICIT[0])
    inputs = [
        JobInput(r.request_id, intake(r, produced_at=FIXED_TIME)) for r in t.requests_of(TWO_MILL)
    ]
    via_job_set = schedule_job_set(
        inputs, default_model(), produced_at=FIXED_TIME, setup_rules=EXPLICIT
    ).schedule
    assert schedule_view(direct) == schedule_view(via_job_set)
