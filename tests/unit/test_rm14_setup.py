"""RM14 — sequence-dependent cross-job changeover (Director tests A-V).

Every expected schedule is hand-computed from the frozen rule (specs/milestones/
RM14-sequence-dependent-changeover.md §9) and never generated by the implementation. Default
capability model: saw01 cut_stock; mill01 face_mill/drill/pocket_mill; lathe01 turn; bench01
deburr; cmm01 inspect. Canonical order is request_id ascending: ID_A < ID_B < ID_C.
"""

from __future__ import annotations

import pytest

import rm11_support as s
import rm14_support as t
from mini_prometheus.intake.request_intake import intake
from mini_prometheus.manufacturing_constraints.capability_model import default_model
